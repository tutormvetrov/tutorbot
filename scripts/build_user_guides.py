"""Generates four DOCX user guides for the bot — one per role.

Usage (from project root, with dev venv active):

    python scripts/build_user_guides.py

Outputs four files under docs/user_guides/:

    user_guide_student_adult.docx
    user_guide_student_school.docx
    user_guide_parent.docx
    user_guide_admin.docx

The script is idempotent — each run rewrites all four files.
Re-run after any noticeable change in main-menu buttons, registration flow,
or new feature blocks. Commit the resulting binaries.
"""
from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.shared import Pt


# ── Output paths ─────────────────────────────────────────────────────────────

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs" / "user_guides"


# ── Tiny helpers ─────────────────────────────────────────────────────────────

def new_doc() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)
    return doc


def add_title(doc: Document, text: str) -> None:
    h = doc.add_heading(text, level=0)
    for run in h.runs:
        run.font.size = Pt(20)


def add_h1(doc: Document, text: str) -> None:
    doc.add_heading(text, level=1)


def add_h2(doc: Document, text: str) -> None:
    doc.add_heading(text, level=2)


def add_paragraph(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def add_bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def add_steps(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Number")


# ── Common building blocks ───────────────────────────────────────────────────

def write_intro_for_student(doc: Document, *, child: bool) -> None:
    add_h1(doc, "О чём этот бот")
    if child:
        add_paragraph(
            doc,
            "Это твой помощник по урокам английского. В нём ты видишь, "
            "когда у тебя занятие, что задано на дом, как идут оплаты и "
            "учебный план. Если что-то непонятно — можно прямо отсюда "
            "написать преподавателю."
        )
    else:
        add_paragraph(
            doc,
            "Это твой помощник по урокам английского: расписание, домашка, "
            "оплаты, учебный план и связь с преподавателем — всё в одном "
            "месте. Бот не заменяет занятия, он просто упрощает рутину."
        )


